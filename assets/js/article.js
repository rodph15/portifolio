  const languageSelect = document.querySelector("#article-language-select");
  const portugueseRegions = new Set(["AO", "BR", "CV", "GQ", "GW", "MZ", "PT", "ST", "TL"]);

  function detectLanguage() {
    const locales = navigator.languages?.length ? navigator.languages : [navigator.language];
    for (const locale of locales) {
      try {
        const parsedLocale = new Intl.Locale(locale);
        if (parsedLocale.language.toLowerCase() === "pt" ||
          (parsedLocale.region && portugueseRegions.has(parsedLocale.region.toUpperCase()))) return "pt";
      } catch (error) {
        if (/^pt(?:-|$)/i.test(locale)) return "pt";
      }
    }
    return "en";
  }

  function setLanguage(language) {
    const selectedLanguage = translations[language] ? language : "en";
    const selectedTranslations = translations[selectedLanguage];
    document.documentElement.lang = selectedLanguage === "pt" ? "pt-BR" : "en";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const translation = selectedTranslations[element.dataset.i18n];
      if (!translation) return;
      const attribute = element.dataset.i18nAttr;
      if (attribute) element.setAttribute(attribute, translation);
      else element.textContent = translation;
    });

    const articleDate = document.querySelector("[data-article-date]");
    articleDate.textContent = new Intl.DateTimeFormat(
      selectedLanguage === "pt" ? "pt-BR" : "en",
      { dateStyle: "medium", timeStyle: "short" }
    ).format(new Date(articleDate.dateTime));
    languageSelect.value = selectedLanguage;
  }

  languageSelect.addEventListener("change", (event) => setLanguage(event.target.value));
